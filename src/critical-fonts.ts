/** وجهٌ واحد مطلوبٌ عند أول رسم: مواصفته المختصرة، ونصٌّ يمثّل نطاقه. */
export interface CriticalFace {
  /** اختصار `font` كما يقبله `FontFaceSet.load`: وزنٌ ومقاسٌ وعائلة. */
  readonly spec: string;
  /**
   * نصٌّ يُمرَّر إلى `FontFaceSet.load` ليختار المقاطع المطلوبة وحدها.
   *
   * ‏`load(spec, text)` لا يحمّل كل مقاطع العائلة، بل ما يتقاطع `unicode-range`
   * له مع النصّ. فالنصّ هنا أداةُ انتقاء لا عيّنةَ عرض: وجودُ مسافةٍ فيه يعني
   * «احمِل المقطع اللاتيني أيضًا»، وغيابُها يعني «العربيّ وحده».
   */
  readonly sample: string;
}

