/**
 * الوجوه الحرجة — ما يجب أن يكون حاضرًا **قبل** أول رسم.
 *
 * ## لماذا هذا الملف موجود أصلًا
 *
 * كل قواعد `@font-face` في `design-system/fonts.css` تحمل `font-display: swap`.
 * ‏`swap` يعني: ارسم بخطّ النظام الآن، وبدّله متى وصل الخطّ الحقيقي. والتبديل
 * يغيّر المقاسات — Cairo يرتفع ‎1.303em فوق خطّ الأساس بينما خطّ نظام macOS
 * يرتفع ‎0.952em، وعرض المحارف يختلف محرفًا محرفًا — فينتقل موضع كل ما تحت
 * النصّ. هذا هو «القفز» الذي يظهر عند كتلة سَطْر: صندوق أُحاديّ العرض
 * ‏(`white-space: pre`) هو أكثر عناصر الشاشة حساسيةً لتغيّر المقاييس.
 *
 * ‏`fonts.css` منسوخ من مشروع الهوية ويجب أن يبقى مطابقًا له بايتًا ببايت، فلا
 * يُصلَح `swap` بتحريره. يُصلَح من الخارج: نُعلن هنا — في طبقة التطبيق — أي
 * الوجوه تحتاجها شاشة الترحيب عند أول رسم، فتقرأ إضافة Vite في `vite.config.ts`
 * هذا الإعلان وتحقن `<link rel="preload">` لكل ملفٍ منها في رأس المستند، فيبدأ
 * تحميلها مع تحليل HTML لا بعد تنفيذ حزمة JS.
 *
 * ## ما تغيّر: لا بوّابةَ انتظارٍ بعد اليوم
 *
 * كان ‏`main.tsx` يؤخّر أول `render` حتى تجهز هذه الوجوه بعينها عبر
 * ‏`FontFaceSet.load`. أُزيلت تلك البوّابة بعد قياسٍ أثبت أنها زائدة: التحميل
 * المسبق وحده يُبقي إزاحة التخطيط التراكمية صفرًا حتى مع كمون شبكةٍ قدره
 * ‎1200ms، بينما يقفز المقياس إلى ‎0.0658 عند نزع التحميل المسبق وحده. الجدول
 * الكامل وضابطه السالب في تعليق `main.tsx`.
 *
 * ولهذا بقيت القائمتان أدناه معًا رغم أن أحدًا لم يعد ينتظر وجهًا وقت التشغيل:
 * قائمة **الملفّات** هي ما يُحقن، وقائمة **الوجوه** هي ما يُبرهَن به أن الأولى
 * كاملة — ‏`critical-fonts.test.ts` يقابل الاثنتين بـ`fonts.css` فيسقط إن
 * استعملت الشاشة عائلةً أو وزنًا لا ملفَّ له في التحميل المسبق. ومصدرٌ واحد
 * للحقيقة لأن الطرفين لا يصحّ أن يفترقا: تحميلٌ مسبق لملفٍّ لا تستعمله الشاشة
 * هدرٌ في زمن أول رسم، ووجهٌ تستعمله الشاشة بلا ملفٍّ محمَّل مسبقًا هو القفزةُ
 * عائدة.
 *
 * ## لماذا لا تُحمَّل السبعة عشر ملفًا
 *
 * التقسيم في `fonts.css` مأخوذ عن Google Fonts، وشكله كالآتي:
 *
 * - **Cairo** خطٌّ متغيّر (محور `wght` من 200 إلى 1000): ثلاثة ملفات فقط،
 *   ‏`cairo-000` عربي و`cairo-001` لاتيني موسّع و`cairo-002` لاتيني. الأوزان
 *   الستّة المعلنة تشير كلّها إلى الملفّات نفسها، فوزنٌ واحد أو ستّة لا يغيّر
 *   عدد التنزيلات.
 * - **Almarai** خطٌّ ثابت: وزنٌ لكل ملف، عربيٌّ ولاتينيّ لكل وزن
 *   ‏(003/004 = 300، و005/006 = 400، و007/008 = 700، و009/010 = 800).
 * - **JetBrains Mono** خطٌّ متغيّر كذلك: ستّة ملفات نطاقاتٍ لا أوزان
 *   ‏(سيريلي وسيريلي موسّع ويوناني وفيتنامي ولاتيني موسّع ولاتيني).
 *
 * فالمطلوب ستّة ملفات من سبعة عشر (‏142 ك.ب من 279): الشاشة عربية بالكامل، ولا
 * حرف سيريليًّا ولا يونانيًّا ولا فيتناميًّا فيها.
 *
 * ## لماذا الملفّ اللاتيني مطلوبٌ لنصٍّ عربيّ خالص
 *
 * ‏`U+0020` — المسافة — يقع في النطاق اللاتيني لا العربي في تقسيم Google. فكل
 * جملةٍ عربية فيها مسافة تستدعي الملفّ اللاتيني أيضًا. إغفاله يترك المسافات
 * وحدها بمقاس خطّ النظام، وعرض المسافة يقرّر مواضع اللفّ في العنوان، فتتغيّر
 * أسطر العنوان عند وصول الخطّ. ولهذا `cairo-002` و`almarai-006` هنا.
 */

