import { createRoot } from 'react-dom/client';

// نظام التصميم يُستورد من مشروع الهوية قراءةً فقط. Vite يجمعه في dist الخاص
// بالمنتج، ولا يكتب شيئًا داخل مجلد الهوية.
import '@ds/fonts.css';
import '@ds/tokens.css';
import '@ds/base.css';
import './app.css';

// الرموز تُحقن كتعريفات داخل المستند: الإشارة عبر ملف خارجي لا تعمل في
// WebKit/Chromium وتفشل صامتة.
import iconSprite from '@ds/icons.svg?raw';
import logoSprite from '@ds/logo.svg?raw';

import App from './app';

/**
 * ## لماذا لا بوّابةَ خطوطٍ قبل أول `render`
 *
 * كانت هنا بوّابة: `whenCriticalFontsReady().then(() => render(…))` بسقف
 * انتظارٍ قدره ثانية. غرضها منعُ القفزة التي يُحدثها `font-display: swap` حين
 * تتبدّل مقاييس الخطّ بعد أول رسم. وقد أُزيلت لأنها كانت تشتري صفرًا بثمنٍ
 * ليس صفرًا:
 *
 * - **الثمن**: تأجيلُ أول رسمٍ للتطبيق *كلّه* — لا شاشة الترحيب وحدها — خلف
 *   وعدٍ أسوأُ حالاته نافذةٌ فارغة لثانيةٍ كاملة إن تعطّل بروتوكول الأصول. وهو
 *   تغييرٌ في سلوك الإقلاع خرج من مهمّةٍ نطاقها شاشةٌ واحدة.
 * - **المكسب**: صفر، مقيسًا.
 *
 * ### القياس، لا الاستنتاج
 *
 * ثلاث حالاتٍ على البناء الإنتاجي في Chrome بلا رأس، بذاكرةٍ مُعطَّلة
 * (`Network.setCacheDisabled`) وشبكةٍ مُبطَّأة (كمونٌ ‎1200ms) كي تصل الخطوط
 * *بعد* أول رسمٍ حتمًا، ورصدُ `layout-shift` عبر `PerformanceObserver`:
 *
 * | الحالة | ‎1080×720 | ‎680×520 |
 * |---|---|---|
 * | بوّابة + تحميل مسبق | ‎0 | ‎0 |
 * | تحميل مسبق وحده (بلا بوّابة) | ‎0 | ‎0 |
 * | بلا تحميلٍ مسبق ولا بوّابة | ‎0.0215 | ‎0.0658 |
 *
 * الصفّ الثالث ضابطٌ سالب، وهو أهمّ الثلاثة: بدونه لا يثبت أن الصفرين فوقه
 * قياسٌ لا عمًى في أداة القياس. ومصادر الإزاحة فيه هي المتوقّعة حرفيًا —
 * ‏`onboarding__panes` ثم `onboarding__title` و`onboarding__lede` — أي القفزةُ
 * التي جاءت البوّابة لتمنعها، ظاهرةً حين يُنزع التحميل المسبق وحده.
 *
 * فالخلاصة: **`<link rel="preload">` هو العلاج، والبوّابة كانت تأمينًا على
 * خطرٍ يدفعه التحميل المسبق أصلًا.** الخطوط ملفّاتٌ مرفقة بالتطبيق يبدأ طلبها
 * مع تحليل HTML، فتصل قبل تنفيذ حزمة JS لا بعده — انظر `preloadCriticalFonts`
 * في `vite.config.ts` و`src/critical-fonts.ts`.
 *
 * ### وفائدةٌ ثانية للإزالة: الخطأ يعود متزامنًا
 *
 * البوّابة كانت `void promise.then(() => { … render … })` بلا `catch`. فأي رمية
 * من `render` — وهي أوّل ما يُنفَّذ من شجرة React — كانت تصير رفضًا غير مُلتقَط
 * يظهر في الطرفية سطرًا غامضًا بلا أثرٍ للمكدّس المفيد، بدل أن تسقط الحزمة عند
 * سطرها. والاستدعاء المتزامن أدناه يعيدها خطأً متزامنًا كما يجب، بلا حاجةٍ إلى
 * `catch` أصلًا: لا وعدَ هنا ليُرفض.
 */

const defs = document.createElement('div');
defs.style.display = 'none';
defs.setAttribute('aria-hidden', 'true');
defs.innerHTML = iconSprite + logoSprite;
document.body.prepend(defs);

const root = document.getElementById('root');
if (!root) throw new Error('#root missing');

createRoot(root).render(<App />);
