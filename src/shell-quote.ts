/**
 * تنسيق أمرٍ صالحٍ للصق في Terminal.
 *
 * ## هذا للعرض والنسخ فقط
 *
 * لا يمرّ ناتج هذا الملف بأي مسار تنفيذ. التطبيق يشغّل `program` و`args`
 * مباشرةً بلا صدفة، فلا يحتاج هروبًا أصلًا — الهروب هنا لأن **المستخدم** قد
 * يلصق الأمر في صدفة، وهي تحتاجه.
 *
 * لو استُعمل هذا النص في التنفيذ لانقلبت المعادلة: خطأ في الهروب يصير ثغرة
 * حقن أوامر. ولذلك لا يوجد في المشروع دالة تأخذ نصًا كهذا وتشغّله؛ حدّ IPC
 * لا يقبل إلا رمز خطة.
 *
 * ## قاعدة الاقتباس
 *
 * الاقتباس المفرد في POSIX حرفيّ تمامًا: كل شيء داخله يفقد معناه الخاص، ولا
 * استثناء إلا الاقتباس المفرد نفسه — لا سبيل لهروبه داخل الاقتباس، فيُغلق
 * الاقتباس ويُكتب المحرف مهروبًا ثم يُفتح من جديد: `'` ← `'\''`.
 *
 * هذا يجعل العربية والمسافات و`$` و`` ` `` و`;` و`&` نصًا حرفيًا.
 */

/** هل الرمز آمن بلا اقتباس؟ قائمة سماح، لا قائمة منع. */
const SAFE = /^[A-Za-z0-9_@%+=:,./-]+$/;

export function shellQuote(token: string): string {
  if (token.length === 0) return "''";
  if (SAFE.test(token)) return token;
  return `'${token.split("'").join("'\\''")}'`;
}

/** يبني سطرًا واحدًا صالحًا للصق. */
export function shellCommand(argv: readonly string[]): string {
  return argv.map(shellQuote).join(' ');
}

/**
 * محارف غير مرئية: تحكّم الاتجاه، ومحارف بلا عرض.
 *
 * تُكتب بترميزها لا بذاتها: محرفٌ غير مرئي داخل شيفرة المصدر يجعل السطر نفسه
 * غير قابل للمراجعة — وهو بالضبط ما نحذّر منه هنا.
 *
 * 061C علامة عربية · 200B..200F فواصل بلا عرض وعلامتا الاتجاه ·
 * 202A..202E الغلاف القديم · 2066..2069 العزل · FEFF علامة ترتيب البايت.
 */
const INVISIBLE = /[\u061C\u200B-\u200F\u202A-\u202E\u2066-\u2069\uFEFF]/;

/** مسافات ليست 0020: تبدو مسافةً ولا تتصرّف مثلها. */
const ODD_SPACE = /[\u00A0\u1680\u2000-\u200A\u202F\u205F\u3000]/;

/**
 * يصف رمزًا للقارئ حين لا يكفي النظر.
 *
 * مسافة في طرف الاسم، أو محرف اتجاه غير مرئي، أو مسافة غير فاصلة — كلها تبدو
 * على الشاشة كأنها لا شيء. الوصف يجعلها مرئية قبل أن يُنفَّذ الأمر.
 */
export function tokenNotes(token: string): string[] {
  const notes: string[] = [];
  if (token !== token.trim()) notes.push('يبدأ أو ينتهي بمسافة');
  if (/ {2,}/.test(token)) notes.push('يحتوي مسافات متتالية');
  if (INVISIBLE.test(token)) notes.push('يحتوي محارف غير مرئية');
  if (ODD_SPACE.test(token)) notes.push('يحتوي مسافة غير اعتيادية');
  if (/[\t\n\r]/.test(token)) notes.push('يحتوي جدولة أو سطرًا جديدًا');
  if (token.includes("'")) notes.push('يحتوي اقتباسًا مفردًا');
  return notes;
}
