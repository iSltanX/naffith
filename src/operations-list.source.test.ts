// @vitest-environment node
/**
 * حارسُ القاعدة الوحيدة، مقروءًا من المصدر نفسه.
 *
 * اختبارات العرض تثبت أن خمس عملياتٍ مخترعة تظهر اليوم؛ وهذا يثبت أن الطريق
 * إلى كسر ذلك مسدود غدًا. الفرق أن خريطةً صغيرة تُضاف «مؤقّتًا» لبطاقةٍ واحدة
 * قد تمرّ من هناك — كل العمليات المحقونة تظل تُرسم — لكنها تسقط هنا.
 *
 * لذلك يُقرأ الملف نصًّا لا يُستورد: المطلوب فحصُ ما كُتب، لا ما ينتج عن
 * تنفيذه. وبيئة الاختبار `node` لأن `jsdom` يعيد كتابة أصل `import.meta.url`
 * إلى عنوان http فيصير مسار المصدر من جذر القرص.
 */
import { readFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';

const SOURCE = readFileSync(new URL('./operations-list.tsx', import.meta.url).pathname, 'utf8');

describe('مصدر قائمة العمليات', () => {
  it('لا يذكر معرّف عمليةٍ ولا فئةً داخلية', () => {
    // الفهرس مِلك النواة. أول معرّف يُكتب هنا هو أول سطرٍ في فهرسٍ ثانٍ.
    expect(SOURCE).not.toMatch(/compress\.folder\.zip|internal\./);
  });

  it('لا يحمل مفاتيح نصوص العمليات', () => {
    // `op.*` مفاتيح تصدرها النواة مع كل عملية. وجودها هنا يعني أن الشاشة
    // صارت تعرف أسماء العمليات بدل أن تعرض ما وصلها.
    expect(SOURCE).not.toMatch(/['"`]op\.[a-z]/);
  });

  it('لا يفرّع على معرّف بطاقة', () => {
    // `card.id` تُمرَّر إلى `onSelect` ولا تُقارَن بشيء ولا تُستعمل مفتاحًا
    // لخريطة. أي `===` أو `[` بعدها يعني أن قرارًا صار يعتمد على العملية.
    expect(SOURCE).not.toMatch(/\.id\s*(===|==|\.startsWith|\.includes)/);
    expect(SOURCE).not.toMatch(/\bswitch\s*\(/);
  });
});
